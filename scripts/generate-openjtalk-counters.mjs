// Extract upstream tables without editing their entries. Only the current
// application's already-pinned Kuromoji dictionary supplies base readings.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),kuromoji=require('../kanji-reading/lab/node_modules/kuromoji');
const source=await readFile('kanji-reading/vendor/open-jtalk/njd_set_digit_rule_utf_8.h','utf8');
const hash=createHash('sha256').update(source).digest('hex');
const clean=source.replace(/\/\*[\s\S]*?\*\//g,'');
const tables={};
for(const m of clean.matchAll(/static const char \*(njd_set_digit_rule_\w+)\[\] = \{([\s\S]*?)\};/g))tables[m[1].replace('njd_set_digit_rule_','')]=[...m[2].matchAll(/"(?:[^"\\]|\\.)*"/g)].map(m=>JSON.parse(m[0]));
const units=new Set();for(const [name,table] of Object.entries(tables))if(name.startsWith('numerative_class'))for(let i=0;i<table.length;i+=name==='numerative_class3'?2:1)units.add(table[i]);
const tokenizer=await new Promise((resolve,reject)=>kuromoji.builder({dicPath:'kanji-reading/lab/node_modules/kuromoji/dict/'}).build((e,t)=>e?reject(e):resolve(t)));
// Unchanged counters such as 枚/台/羽 need no upstream sound-change class,
// but still need whole-number readings. Obtain them from the existing dictionary.
const dictionary=tokenizer.viterbi_builder.token_info_dictionary;
for(let id=0;id+10<=dictionary.dictionary.buffer.length;id+=10){const f=dictionary.getFeatures(id).split(',');if(f.slice(1,5).includes('助数詞'))units.add(f[0]);}
const bases={};
for(const unit of [...units].sort()){
 const text='3'+unit,tokens=tokenizer.tokenize(text),tail=tokens.find(t=>t.word_position===2&&t.surface_form===unit&&t.pos_detail_2==='助数詞'&&t.word_type!=='UNKNOWN'&&/^[ァ-ヺー]+$/.test(t.reading||''));
 if(tail)bases[unit]=tail.reading;
}
const license=await readFile('kanji-reading/vendor/open-jtalk/COPYING','utf8');
const output=license+'\n// Generated by scripts/generate-openjtalk-counters.mjs; do not edit tables.\n// Open JTalk 1.11 header SHA-256: '+hash+'\n// Base readings: existing Kuromoji 0.1.2 IPADIC; see licenses/NOTICE.kuromoji-IPADIC.md.\nexport const tables='+JSON.stringify(tables,null,1)+';\nexport const counterBases='+JSON.stringify(bases,null,1)+';\n';
if(process.argv.includes('--check')){if(await readFile('kanji-reading/lab/src/openjtalk-counter-data.mjs','utf8')!==output)throw Error('Open JTalk data is stale');}
else await writeFile('kanji-reading/lab/src/openjtalk-counter-data.mjs',output);
console.log(JSON.stringify({tables:Object.keys(tables).length,upstreamUnits:units.size,dictionaryCounters:Object.keys(bases).length,sha256:hash}));
